"""Generate engine/src/script/game_api_names.inc: the names of every C function the game
registers with Lua. libKRHP.so registers them one by one in RegisterScriptFunctions()
(CLuaScriptManager::RegisterCFunction(name, fn)); this follows its ARM code, where each
name and function is a PC-relative literal (ldr rX, [pc, #n]; add rX, pc, rX).

The engine registers all of them so level scripts never call nil; the ones it does
not implement yet log their first use and return nothing.

    python3 tools/gen_script_api.py work/bin/libKRHP.so [--list]   (--list: name and C function)
"""
import re
import struct
import subprocess
import sys
from pathlib import Path


def symbols(lib):
    out = subprocess.run(["nm", "-C", lib], capture_output=True, text=True, check=True).stdout
    syms = {}
    for line in out.splitlines():
        p = line.split(None, 2)
        if len(p) == 3 and not p[2].startswith("$"):
            syms.setdefault(int(p[0], 16), p[2])
    return syms


def registered(lib):
    data = Path(lib).read_bytes()
    syms = symbols(lib)
    by_name = {v: k for k, v in syms.items()}
    start = by_name["RegisterScriptFunctions()"]
    end = min(a for a in syms if a > start)
    reg_fn = by_name["CLuaScriptManager::RegisterCFunction(char const*, int (*)(lua_State*))"]
    sections = []
    for line in subprocess.run(["readelf", "-SW", lib], capture_output=True, text=True, check=True).stdout.splitlines():
        m = re.search(r"\]\s+\S+\s+PROGBITS\s+([0-9a-f]+) ([0-9a-f]+) ([0-9a-f]+)", line)
        if m:
            sections.append(tuple(int(x, 16) for x in m.groups()))

    def file_offset(va):
        for v, o, s in sections:
            if v <= va < v + s:
                return o + va - v
        raise ValueError(hex(va))

    def cstr(va):
        off = file_offset(va)
        return data[off:data.index(b"\0", off)].decode("latin1")

    asm = subprocess.run(["llvm-objdump", "-d", f"--start-address={start:#x}", f"--stop-address={end:#x}", lib],
                         capture_output=True, text=True, check=True).stdout
    regs, out = {}, []
    for line in asm.splitlines():
        m = re.match(r"\s*([0-9a-f]+):\s+[0-9a-f]{8}\s+(\S+)\s+([^@]*)", line)
        if not m:
            continue
        at, op, args = int(m.group(1), 16), m.group(2), m.group(3).strip()
        if op == "ldr" and (a := re.match(r"(\w+), \[pc, #(-?(?:0x)?[0-9a-f]+)\]$", args)):
            regs[a.group(1)] = struct.unpack_from("<I", data, file_offset(at + 8 + int(a.group(2), 0)))[0]
        elif op == "add" and (a := re.match(r"(\w+), pc, (\w+)$", args)):
            regs[a.group(1)] = (regs.get(a.group(2), 0) + at + 8) & 0xFFFFFFFF
        elif op == "mov" and (a := re.match(r"(\w+), (r\d+)$", args)):
            regs[a.group(1)] = regs.get(a.group(2))
        elif op == "bl":
            if f"{reg_fn:#x}" in args or f"{reg_fn:x} " in args:
                fn = regs.get("r2", 0) & ~1
                out.append((cstr(regs["r1"]), syms.get(fn, hex(fn))))
            for r in ("r0", "r1", "r2", "r3", "r12", "lr"):
                regs.pop(r, None)
    return out


def main(argv):
    lib = next((a for a in argv[1:] if not a.startswith("--")), "work/bin/libKRHP.so")
    pairs = registered(lib)
    if "--list" in argv:
        for name, fn in pairs:
            print(f"{name}\t{fn}")
        return
    names = sorted({n for n, _ in pairs})
    dest = Path(__file__).resolve().parent.parent / "engine/src/script/game_api_names.inc"
    body = "".join(f'"{n}",\n' for n in names)
    dest.write_text("// Generated by tools/gen_script_api.py: Lua functions the game registers.\n" + body)
    print(f"{len(names)} names -> {dest}")


if __name__ == "__main__":
    main(sys.argv)
