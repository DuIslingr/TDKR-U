#!/usr/bin/env python3
"""Regenerate tools/lvc_specs.py from the decompiled loaders in work/decomp.

Inputs (run from the repository root):
  specs.json            skel2spec.py over loaders.c (every ::Load) and levelobjs.c
  component_loads.json  component hash -> class and its Load (vtable slot +8), for the
                        components CComponentFactory::CreateComponent builds
  templates.json        component hash -> template class and its Load (vtable slot +0x10),
                        from GenerateComponentTemplate

TDKR's component ids are 32-bit hashes; N.O.V.A. 3's were small integers with a
hand-kept component_ids.txt. See ANALYSIS.md for how the two maps were made.
"""
import json
import re

# Level-structure readers used by CLevel::LoadNextObject (see tools/lvc.py LEVEL_TYPES).
LEVEL_LOADS = [
    "CComponentBase::Load", "CComponentMesh::Load", "CComponentLight::Load",
    "CComponentBuiltinCylinder::Load", "CTemplateLevelProperties::Load", "CTemplateZone::Load",
    "CTemplateMetaZone::Load", "CTemplatePortal::Load", "CSpawnPointObject::Create",
    "CWayPointObject::Load", "CTemplateOccluder::Load", "CZone::LoadIrradianceVolume",
    "CTemplateGlobalIllumination::Load", "CTemplateBakeGroup::Load",
    "CComponentBaseWorldBox::Load", "CComponentBuiltinBox::Load",
]

specs = json.load(open("work/decomp/specs.json"))
comps = {int(k, 16): v for k, v in json.load(open("work/decomp/component_loads.json")).items()}
templates = {int(k, 16): v for k, v in json.load(open("work/decomp/templates.json")).items()}

need, stack = set(), [v["load"] for v in comps.values()] + [v["load"] for v in templates.values()] + LEVEL_LOADS
while stack:
    k = stack.pop()
    if k in need or k not in specs:
        continue
    need.add(k)
    stack += re.findall(r"<([^>]+)>", specs[k]["spec"])

lines = ['"""Read specs for The Dark Knight Rises .lvc and gol.bin files.', '',
         "Generated by tools/ghidra_scripts/gen_lvc_specs.py from the game's decompiled",
         "loaders. Tokens: i f h c s v, [ ... ] = int-count-prefixed list, <Name::Load> =",
         "nested loader. Do not edit by hand; regenerate instead (hand corrections go in",
         'lvc.SPEC_OVERRIDES).', '"""', '',
         "# CComponentFactory::CreateComponent: component hash -> (class, its Load)",
         "COMPONENT_LOADS = {"]
lines += [f'    {k:#010x}: ("{v["class"]}", "{v["load"]}"),' for k, v in sorted(comps.items())]
lines += ["}", "", "# GenerateComponentTemplate: component hash -> (template class, its Load)", "TEMPLATE_LOADS = {"]
lines += [f'    {k:#010x}: ("{v["class"]}", "{v["load"]}"),' for k, v in sorted(templates.items())]
lines += ["}", "", "SPECS = {"] + [f'    "{k}": "{specs[k]["spec"]}",' for k in sorted(need)] + ["}", ""]
open("tools/lvc_specs.py", "w").write("\n".join(lines))
missing = sorted({v["load"] for v in list(comps.values()) + list(templates.values())} - set(specs))
print("components", len(comps), "templates", len(templates), "specs", len(need), "loaders without a spec:", missing)
