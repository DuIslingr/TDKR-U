#!/usr/bin/env python3
"""Generate engine/src/assets/level_specs.inc from tools/lvc_specs.py and lvc.py.

The engine and the Python tools then share one source of truth for the level and
object-library read specs. Run after regenerating lvc_specs.py.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
import lvc  # noqa: E402
import lvc_specs  # noqa: E402

OUT = ROOT.parent / "engine" / "src" / "assets" / "level_specs.inc"


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    lines = [
        "// Generated by tools/gen_engine_specs.py from tools/lvc_specs.py and tools/lvc.py.",
        "// Do not edit; regenerate instead.",
        "// Spec tokens: i f h H c s v, [ ... ] = int-count-prefixed list, <Name::Load> = nested loader.",
        "",
        "// CComponentFactory::CreateComponent: component hash -> the Load that reads its level data.",
        "static const std::pair<int, const char*> kComponentLoads[] = {",
    ]
    lines += [f"    {{{cid:#010x}, {cstr(load)}}},   // {cls}"
              for cid, (cls, load) in sorted(lvc_specs.COMPONENT_LOADS.items())]
    lines += ["};", "", "// GenerateComponentTemplate: component hash -> the template's Load (gol.bin, and",
              "// level data of components the factory does not build).",
              "static const std::pair<int, const char*> kTemplateLoads[] = {"]
    lines += [f"    {{{cid:#010x}, {cstr(load)}}},   // {cls}"
              for cid, (cls, load) in sorted(lvc_specs.TEMPLATE_LOADS.items())]
    specs = dict(lvc_specs.SPECS)
    specs.update(lvc.SPEC_OVERRIDES)
    lines += ["};", "", "// Loader name -> spec (generated specs with lvc.SPEC_OVERRIDES applied).",
              "static const std::pair<const char*, const char*> kLoaderSpecs[] = {"]
    lines += [f"    {{{cstr(k)}, {cstr(v)}}}," for k, v in sorted(specs.items())]
    lines += ["};", "", "// CLevel::LoadNextObject: level-structure type -> (kind, spec).",
              "struct LevelTypeSpec {", "    int type;", "    const char* kind;", "    const char* spec;", "};",
              "static const LevelTypeSpec kLevelTypes[] = {"]
    lines += [f"    {{{t:#07x}, {cstr(kind)}, {cstr(spec)}}},"
              for t, (kind, spec) in sorted(lvc.LEVEL_TYPES.items())]
    lines += ["};", "",
              f"static const int kCompBaseHash = {lvc.COMP_BASE:#010x};",
              f"static const int kCompMeshHash = {lvc.COMP_MESH:#010x};",
              f"static const int kCompGroupHash = {lvc.COMP_GROUP:#010x};   // read whatever its flag",
              f"static const char* const kGroupBuiltinSpec = {cstr(lvc.GROUP_BUILTIN)};",
              f"static const char* const kBaseLoader = {cstr('CComponentBase::Load')};",
              f"static const char* const kMeshLoader = {cstr('CComponentMesh::Load')};", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(specs)} loader specs)")


if __name__ == "__main__":
    main()
